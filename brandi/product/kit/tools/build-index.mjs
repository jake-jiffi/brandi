#!/usr/bin/env node
/**
 * Write components/system/index.ts: every export of every file in components/system, so adding a
 * component is adding its file. Run by tools/build-canvas.mjs and by the skill's starter generator.
 *
 *   node tools/build-index.mjs [--check]
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

export function indexSource(dir) {
  const files = readdirSync(dir).filter((f) => /\.tsx?$/.test(f) && f !== "index.ts" && !f.endsWith(".d.ts")).sort()
  const lines = ["// Generated by tools/build-index.mjs from the files beside it. Add a component by adding its file.", ""]
  for (const f of files) {
    const src = readFileSync(path.join(dir, f), "utf8")
    const names = new Set()
    for (const m of src.matchAll(/^export (?:const|function|class) ([A-Z]\w*)/gm)) names.add(m[1])
    for (const m of src.matchAll(/^export \{([^}]+)\}/gm)) {
      for (const part of m[1].split(",")) {
        const name = part.trim().split(/\s+as\s+/).pop()
        if (/^[A-Z]\w*$/.test(name)) names.add(name)
      }
    }
    const types = new Set([...src.matchAll(/^export (?:type|interface) ([A-Z]\w*)/gm)].map((m) => m[1]))
    const mod = `./${f.replace(/\.tsx?$/, "")}`
    if (names.size) lines.push(`export { ${[...names].sort().join(", ")} } from "${mod}"`)
    if (types.size) lines.push(`export type { ${[...types].sort().join(", ")} } from "${mod}"`)
  }
  return `${lines.join("\n")}\n`
}

export function writeIndex(root) {
  const dir = path.join(root, "components", "system")
  const file = path.join(dir, "index.ts")
  const next = indexSource(dir)
  if (!existsSync(file) || readFileSync(file, "utf8") !== next) writeFileSync(file, next)
  return file
}

const invoked = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invoked) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
  if (process.argv.includes("--check")) {
    const file = path.join(root, "components", "system", "index.ts")
    if (!existsSync(file) || readFileSync(file, "utf8") !== indexSource(path.dirname(file))) {
      process.stderr.write("components/system/index.ts is out of date: run node tools/build-index.mjs\n")
      process.exitCode = 1
    }
  } else {
    writeIndex(root)
  }
}
