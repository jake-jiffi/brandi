/**
 * Brandi product layer: lib/brand.ts, the brand's marks and character as the product uses them.
 *
 * The kit's file holds the types and a placeholder mark. `brandi product starter` replaces the
 * placeholder with the brand's own files: the ones product.json's `brand` block names (route B, or
 * any override), otherwise brand.json's logo master (route A). Each mark is inlined after a safety
 * pass. A value the record does not hold keeps the kit's default, and the file says which.
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

export const RENDITIONS = ['full', 'full-on-dark', 'full-ink', 'symbol', 'symbol-on-dark', 'symbol-ink'];
export const CHARACTER_STATES = ['welcome', 'working', 'done', 'caught-up', 'needs-person', 'nothing-found', 'could-not-load', 'help'];
export const LOGO_DEFAULTS = { height: 24, minHeight: 16, symbolMinHeight: 16, clearSpace: 0.25 };
export const BRAND_MARKER = '// Generated by brandi product starter';
const PLACEHOLDER = '// PLACEHOLDER.';

/** One SVG, ready to inline: no prolog, comments, metadata or fixed size, and nothing that runs or reaches outside. */
export function cleanSvg(svg, where = 'a mark') {
  let s = String(svg)
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!DOCTYPE[\s\S]*?>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/gi, '')
    .replace(/\son[a-z]+\s*=\s*("[^"]*"|'[^']*')/gi, '');
  if (/<script\b|<foreignObject\b/i.test(s)) throw new Error(`${where} carries a script or a foreignObject. Export the outlined artwork without them.`);
  if (/(?:xlink:)?href\s*=\s*["'](?!#)/i.test(s)) throw new Error(`${where} links outside itself (an image or a font). Outline it so the file stands alone.`);
  const open = /<svg\b[^>]*>/i.exec(s);
  if (!open) throw new Error(`${where} is not an SVG.`);
  let tag = open[0];
  if (!/\sviewBox=/.test(tag)) {
    const w = /\swidth="([\d.]+)/.exec(tag)?.[1];
    const h = /\sheight="([\d.]+)/.exec(tag)?.[1];
    if (!w || !h) throw new Error(`${where} has no viewBox and no width and height to make one from.`);
    tag = tag.replace(/^<svg/i, `<svg viewBox="0 0 ${w} ${h}"`);
  }
  tag = tag.replace(/\s(?:width|height)="[^"]*"/g, '');
  return s.replace(open[0], tag).trim();
}

/** The one-ink rendition from a single-colour master: every ink becomes currentColor, so the mark takes the text colour. */
export function toInk(svg) {
  let s = svg
    .replace(/\b(fill|stroke)="(?!none|currentColor|url\()[^"]*"/gi, '$1="currentColor"')
    .replace(/\b(fill|stroke)\s*:\s*(?!none|currentColor|url\()[^;"]+/gi, '$1:currentColor');
  // An element with no fill paints black, which is not the text colour.
  if (!/<svg\b[^>]*\sfill=/i.test(s)) s = s.replace(/<svg\b/i, '<svg fill="currentColor"');
  return s;
}

const aspectOf = (svg) => {
  const vb = /\sviewBox="([^"]+)"/.exec(svg)?.[1].trim().split(/[\s,]+/).map(Number);
  return vb && vb[2] > 0 && vb[3] > 0 ? vb[3] / vb[2] : null;
};

/** "Leave clear space on every side equal to half the height of the mark" as 0.5. */
export function clearSpaceRatio(rule) {
  if (typeof rule === 'number') return rule;
  const m = /equal to (half|a third|a quarter|one quarter|(\d*\.?\d+))\b/i.exec(String(rule ?? ''));
  if (!m) return null;
  return m[2] ? Number(m[2]) : { half: 0.5, 'a third': 1 / 3, 'a quarter': 0.25, 'one quarter': 0.25 }[m[1].toLowerCase()];
}

/**
 * Where the marks come from: { from, name, files: { rendition: path }, inkFrom, logo, character, base }.
 * Null when nothing names a mark, and the kit's placeholder stays.
 */
export function brandSources({ product = {}, brand = null, productDir, brandRoot }) {
  const block = product.brand;
  if (block?.marks?.full) {
    return { from: 'product/product.json', name: block.name ?? product.productName ?? brand?.meta?.name ?? null, files: block.marks, inkFrom: null, logo: block.logo ?? {}, character: block.character ?? null, base: productDir };
  }
  const files = brand?.identity?.logo?.files ?? [];
  const role = (r) => files.find((f) => f.role === r)?.path ?? null;
  if (!role('primary')) return null;
  const logo = {};
  const ratio = clearSpaceRatio(brand.identity.logo.clearSpace);
  if (ratio) logo.clearSpace = ratio;
  if (brand.identity.logo.minSize?.screenPx) logo.minLongSide = brand.identity.logo.minSize.screenPx;
  return {
    from: "brand/brand.json's logo master",
    name: brand.meta?.name ?? null,
    files: { full: role('primary'), ...(role('mono-white') ? { 'full-on-dark': role('mono-white') } : {}) },
    inkFrom: role('mono-black'),
    logo,
    character: null,
    base: brandRoot,
  };
}

/**
 * The generated part of lib/brand.ts, and any stills to copy into public/brand/. Throws, naming the
 * file, when a mark is missing or unsafe.
 */
export function brandConstant(src, { publicDir = null } = {}) {
  const read = (rel, what) => {
    const file = path.resolve(src.base, rel);
    if (!existsSync(file)) throw new Error(`${what}: ${rel} does not exist (from ${src.from}).`);
    return { file, text: readFileSync(file, 'utf8') };
  };
  const marks = {};
  for (const [rendition, rel] of Object.entries(src.files ?? {})) {
    if (!RENDITIONS.includes(rendition)) throw new Error(`${src.from} names a mark "${rendition}"; the renditions are ${RENDITIONS.join(', ')}.`);
    // An ink rendition is one colour by definition, so whatever its file's ink, it takes the text colour.
    if (rel) marks[rendition] = (rendition.endsWith('-ink') ? toInk : (x) => x)(cleanSvg(read(rel, `the ${rendition} mark`).text, rel));
  }
  if (src.inkFrom && !marks['full-ink']) marks['full-ink'] = toInk(cleanSvg(read(src.inkFrom, 'the one-ink mark').text, src.inkFrom));

  const kept = [];
  const logo = {};
  for (const key of Object.keys(LOGO_DEFAULTS)) {
    if (typeof src.logo?.[key] === 'number') logo[key] = src.logo[key];
  }
  // Brandi records the smallest size along the long side; the product sizes a logo by its height.
  const aspect = aspectOf(marks.full);
  if (logo.minHeight == null && src.logo?.minLongSide && aspect) logo.minHeight = Math.max(1, Math.ceil(src.logo.minLongSide * Math.min(aspect, 1)));
  for (const [key, value] of Object.entries(LOGO_DEFAULTS)) {
    if (logo[key] != null) continue;
    // With no symbol of its own on record, the symbol's floor is the logo's, when that came from the record.
    if (key === 'symbolMinHeight' && !kept.includes('minHeight')) { logo[key] = logo.minHeight; continue; }
    logo[key] = value;
    kept.push(key);
  }
  if (logo.height < logo.minHeight) logo.height = logo.minHeight;

  let character = null;
  const stills = [];
  if (src.character?.poses) {
    const poses = (map) => {
      const out = {};
      for (const [state, rel] of Object.entries(map ?? {})) {
        if (!CHARACTER_STATES.includes(state)) throw new Error(`${src.from} gives the character a "${state}" pose; the states are ${CHARACTER_STATES.join(', ')}.`);
        if (/\.svg$/i.test(rel)) { out[state] = cleanSvg(read(rel, `the ${state} pose`).text, rel); continue; }
        const { file } = read(rel, `the ${state} pose`);
        stills.push(file);
        out[state] = `/brand/${path.basename(file)}`;
      }
      return out;
    };
    character = { name: src.character.name ?? src.name ?? 'Character', poses: poses(src.character.poses) };
    if (src.character.flat) character.flat = poses(src.character.flat);
  }
  if (publicDir && stills.length) {
    mkdirSync(publicDir, { recursive: true });
    for (const f of stills) copyFileSync(f, path.join(publicDir, path.basename(f)));
  }

  const json = (v) => JSON.stringify(v);
  const lines = [
    `${BRAND_MARKER} from ${src.from}. Change the files there and run it again;`,
    '// a hand edit here is undone by the next run.',
    kept.length ? `// The record holds no ${kept.join(', ')}, so ${kept.length === 1 ? 'it keeps the kit default' : 'they keep the kit defaults'} until it does.` : null,
    '',
    'export const BRAND: Brand = {',
    `  name: ${json(src.name ?? 'Product')},`,
    '  marks: {',
    ...Object.entries(marks).map(([k, v]) => `    ${json(k)}: ${json(v)},`),
    '  },',
    `  logo: { height: ${logo.height}, minHeight: ${logo.minHeight}, symbolMinHeight: ${logo.symbolMinHeight}, clearSpace: ${Number(logo.clearSpace.toFixed(3))} },`,
  ].filter((l) => l !== null);
  if (character) {
    lines.push('  character: {', `    name: ${json(character.name)},`, '    poses: {', ...Object.entries(character.poses).map(([k, v]) => `      ${json(k)}: ${json(v)},`), '    },');
    if (character.flat) lines.push('    flat: {', ...Object.entries(character.flat).map(([k, v]) => `      ${json(k)}: ${json(v)},`), '    },');
    lines.push('  },');
  }
  lines.push('}', '');
  return { source: lines.join('\n'), kept, marks: Object.keys(marks), stills: stills.map((f) => path.basename(f)), character: Boolean(character) };
}

/**
 * The whole file: the types from the current lib/brand.ts, then the brand's constant. Null when the
 * file has neither the placeholder nor the generated marker, because then it is the product's own.
 */
export function brandModule(current, generated) {
  const at = [PLACEHOLDER, BRAND_MARKER].map((m) => current.indexOf(`\n${m}`)).filter((i) => i >= 0);
  if (!at.length) return null;
  return `${current.slice(0, Math.min(...at) + 1)}${generated}`;
}

export default { cleanSvg, toInk, clearSpaceRatio, brandSources, brandConstant, brandModule, RENDITIONS, CHARACTER_STATES, LOGO_DEFAULTS, BRAND_MARKER };
