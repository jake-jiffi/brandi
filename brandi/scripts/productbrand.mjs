/** One SVG, ready to inline: no prolog, comments, metadata or fixed size, and nothing that runs or reaches outside. */
export function cleanSvg(svg, where = 'a mark') {
  let s = String(svg)
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!DOCTYPE[\s\S]*?>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/gi, '')
    .replace(/\son[a-z]+\s*=\s*("[^"]*"|'[^']*')/gi, '');
  if (/<script\b|<foreignObject\b/i.test(s)) throw new Error(`${where} carries a script or a foreignObject. Export the outlined artwork without them.`);
  if (/(?:xlink:)?href\s*=\s*["'](?!#)/i.test(s)) throw new Error(`${where} links outside itself (an image or a font). Outline it so the file stands alone.`);
  const open = /<svg\b[^>]*>/i.exec(s);
  if (!open) throw new Error(`${where} is not an SVG.`);
  let tag = open[0];
  if (!/\sviewBox=/.test(tag)) {
    const w = /\swidth="([\d.]+)/.exec(tag)?.[1];
    const h = /\sheight="([\d.]+)/.exec(tag)?.[1];
    if (!w || !h) throw new Error(`${where} has no viewBox and no width and height to make one from.`);
    tag = tag.replace(/^<svg/i, `<svg viewBox="0 0 ${w} ${h}"`);
  }
  tag = tag.replace(/\s(?:width|height)="[^"]*"/g, '');
  return inlineClassStyles(s.replace(open[0], tag).trim());
}

// The CSS properties SVG also takes as presentation attributes. A rule setting anything else stays a rule.
const PRESENTATION = new Set(['fill', 'fill-opacity', 'fill-rule', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin',
  'stroke-miterlimit', 'stroke-dasharray', 'stroke-dashoffset', 'stroke-opacity', 'opacity', 'clip-rule', 'display', 'visibility',
  'color', 'font-family', 'font-size', 'font-weight', 'font-style', 'letter-spacing', 'text-anchor']);

/**
 * Class rules written onto the elements as attributes, and the stylesheet dropped. Brand exports style
 * their paths through `<style>.cls-1{fill:...}</style>`: a stylesheet in a mark leaks into the page it
 * is inlined in, and mail clients strip it, so an email's logo drew black. Only plain class selectors
 * setting presentation properties are inlined, in the cascade's own order (a later rule wins, a rule
 * beats a presentation attribute, an inline style beats both). Anything else leaves the file as it was,
 * for scopeClasses to keep to itself.
 */
export function inlineClassStyles(svg) {
  const blocks = [...svg.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)];
  if (!blocks.length) return svg;
  const rules = [];
  for (const [, raw] of blocks) {
    const css = raw.replace(/\/\*[\s\S]*?\*\//g, '').replace(/<!\[CDATA\[|\]\]>/g, '');
    if (css.replace(/[^{}]+\{[^{}]*\}/g, '').trim()) return svg;
    for (const [, head, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const selectors = head.split(',').map((x) => x.trim()).filter(Boolean);
      if (!selectors.every((x) => /^\.[A-Za-z_][\w-]*$/.test(x))) return svg;
      const decls = body.split(';').map((d) => d.trim()).filter(Boolean).map((d) => [d.slice(0, d.indexOf(':')).trim().toLowerCase(), d.slice(d.indexOf(':') + 1).trim()]);
      if (!decls.every(([prop, value]) => PRESENTATION.has(prop) && value && !/!important|var\(/i.test(value))) return svg;
      for (const sel of selectors) rules.push({ cls: sel.slice(1), decls });
    }
  }
  const out = svg.replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '').replace(/<([A-Za-z][\w:-]*)(\s[^<>]*?)?(\/?)>/g, (tag, name, attrs = '', self) => {
    const cls = /\sclass\s*=\s*"([^"]*)"/i.exec(attrs);
    if (!cls) return tag;
    const own = cls[1].split(/\s+/).filter(Boolean);
    const props = new Map();
    for (const r of rules) if (own.includes(r.cls)) for (const [prop, value] of r.decls) props.set(prop, value);
    const inline = new Set((/\sstyle\s*=\s*"([^"]*)"/i.exec(attrs)?.[1] ?? '').split(';').map((d) => d.split(':')[0].trim().toLowerCase()).filter(Boolean));
    let rest = attrs;
    let added = '';
    for (const [prop, value] of props) {
      if (inline.has(prop)) continue;
      const existing = new RegExp(`\\s${prop}\\s*=\\s*"[^"]*"`, 'i');
      if (existing.test(rest)) rest = rest.replace(existing, ` ${prop}="${value}"`);
      else added += ` ${prop}="${value}"`;
    }
    return `<${name}${rest.replace(cls[0], added)}${self}>`;
  });
  return out.replace(/<defs\b[^>]*>\s*<\/defs>/gi, '').replace(/<defs\s*\/>/gi, '');
}

/**
 * The viewBox cut to the ink. Brand files carry their clear space inside the viewBox, so at 20px tall
 * the letters come out 9px; the product applies clear space in layout instead.
 */
export function tighten(svg) {
  const ink = inkBounds(svg);
  const box = viewBox(svg);
  if (!ink || !box || ink.width <= 0 || ink.height <= 0) return svg;
  const slack = (box.width - ink.width) / box.width + (box.height - ink.height) / box.height;
  if (slack < 0.02) return svg;
  const r = (n) => Number(n.toFixed(2));
  return svg.replace(/(<svg\b[^>]*\sviewBox=")[^"]*(")/i, `$1${r(ink.x)} ${r(ink.y)} ${r(ink.width)} ${r(ink.height)}$2`);
}

/**
 * A file's class names, prefixed so they are its own. Brand exports style their paths through
 * `<style>.cls-1 { fill: ... }</style>`, and a `<style>` inside an inlined SVG applies to the whole
 * page: with the light and dark renditions side by side, the last `.cls-1` painted both, and a navy
 * wordmark drew white on a light ground.
 */
export function scopeClasses(svg, prefix) {
  const names = new Set();
  for (const m of svg.matchAll(/\sclass\s*=\s*"([^"]*)"/gi)) for (const n of m[1].split(/\s+/).filter(Boolean)) names.add(n);
  if (!names.size) return svg;
  const escape = (n) => n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  let out = svg.replace(/(\sclass\s*=\s*")([^"]*)(")/gi, (_, a, list, b) => `${a}${list.split(/\s+/).filter(Boolean).map((n) => `${prefix}${n}`).join(' ')}${b}`);
  out = out.replace(/(<style\b[^>]*>)([\s\S]*?)(<\/style>)/gi, (_, open, css, close) => {
    let scoped = css;
    for (const n of names) scoped = scoped.replace(new RegExp(`\\.${escape(n)}(?![\\w-])`, 'g'), `.${prefix}${n}`);
    return `${open}${scoped}${close}`;
  });
  return out;
}

const NAMED_INKS = { black: '#000000', white: '#ffffff' };

/**
 * Whether a drawing is one dark ink: every colour it paints is the same near-black, or it paints none and so draws
 * black by default. A brand's black line drawings vanished on a dark ground; drawn in currentColor they follow the
 * text there instead. A drawing in a colour (a green, a navy) or in more than one keeps its own colours, because
 * taking the text colour would recolour it on a light ground too. A gradient or pattern is never one ink.
 */
export function oneDarkInk(svg) {
  const inks = new Set();
  for (const [, raw] of String(svg).matchAll(/\b(?:fill|stroke)\s*[:=]\s*["']?([^;"'}\s>]+)/gi)) {
    const v = raw.toLowerCase();
    if (v === 'none' || v === 'transparent' || v === 'currentcolor') continue;
    if (v.startsWith('url(')) return false;
    inks.add(NAMED_INKS[v] ?? v.replace(/^#([0-9a-f])([0-9a-f])([0-9a-f])$/, '#$1$1$2$2$3$3'));
  }
  if (inks.size > 1) return false;
  const [ink = '#000000'] = inks;
  if (!/^#[0-9a-f]{6}$/.test(ink)) return false;
  const c = toOklch(ink);
  return c.L < 0.35 && c.C < 0.04;
}

/** The one-ink rendition from a single-colour master: every ink becomes currentColor, so the mark takes the text colour. */
export function toInk(svg) {
  let s = svg
    .replace(/\b(fill|stroke)="(?!none|currentColor|url\()[^"]*"/gi, '$1="currentColor"')
    .replace(/\b(fill|stroke)\s*:\s*(?!none|currentColor|url\()[^;"}]+/gi, '$1:currentColor');
  // An element with no fill paints black, which is not the text colour.
  if (!/<svg\b[^>]*\sfill=/i.test(s)) s = s.replace(/<svg\b/i, '<svg fill="currentColor"');
  return s;
}

const aspectOf = (svg) => {
  const vb = /\sviewBox="([^"]+)"/.exec(svg)?.[1].trim().split(/[\s,]+/).map(Number);
  return vb && vb[2] > 0 && vb[3] > 0 ? vb[3] / vb[2] : null;
};

/**
 * How much wider than tall a symbol may be. A symbol fills a square place: the icons rail's home control is a 40px
 * square, which holds one 24px tall up to 36px wide. A signature 2.38 times its height, used as the symbol, was drawn
 * 107px wide there and overflowed the rail.
 */
export const SYMBOL_MAX_ASPECT = 1.5;

const AMOUNTS = { half: 0.5, 'a half': 0.5, 'one half': 0.5, 'a third': 1 / 3, 'one third': 1 / 3, 'a quarter': 0.25, 'one quarter': 0.25, 'a fifth': 0.2, 'one fifth': 0.2, 'a tenth': 0.1, 'one tenth': 0.1, twice: 2, double: 2 };
const WHOLE = String.raw`(?:the\s+)?(?:whole\s+|full\s+|primary\s+)?(?:mark|logo|lockup)`;
// The whole, and not a part named after it: "the logo's tagline" and "the logo symbol" are parts.
const NOT_A_PART = String.raw`(?!\s*['’]s\b)(?!\s+(?:symbol|icon|ear|letter|tagline|signature|monogram|wordmark|type)\b)`;
const CLEAR = new RegExp(String.raw`(?:(${Object.keys(AMOUNTS).join('|')}|\d*\.?\d+\s*(?:%|per\s?cent)|\d*\.?\d+(?:\s*(?:x|times))?)\s+(?:of\s+)?|equal to\s+)(?:the\s+)?(?:(height|width)\s+of\s+${WHOLE}\b${NOT_A_PART}|${WHOLE}(?:'s|s')?\s+(height|width)\b)`, 'i');

/**
 * A clear-space rule as a share of the logo's height: "equal to half the height of the mark" is 0.5, "25% of the
 * logo's height" 0.25, "twice the height of the logo" 2. A share of the logo's width needs the mark's shape, its
 * height over its width (`aspect`). A part of the mark ("one e of the signature", the cap height) is not the mark,
 * and its size is not known from here, so it is null: the starter prints the words instead.
 */
export function clearSpaceRatio(rule, { aspect = null } = {}) {
  if (typeof rule === 'number') return rule;
  const m = CLEAR.exec(String(rule ?? ''));
  if (!m) return null;
  const amount = (m[1] ?? '').toLowerCase().trim();
  const share = !amount ? 1 : AMOUNTS[amount] ?? (/%|cent$/.test(amount) ? Number.parseFloat(amount) / 100 : Number.parseFloat(amount));
  if (!(share > 0)) return null;
  if ((m[2] ?? m[3]).toLowerCase() === 'height') return share;
  return aspect > 0 ? share / aspect : null;
}

/**
 * The smallest size on screen of the mark the starter draws, along its long side: the minSizes entry whose variant
 * names that file (through variants[]), or one named for the primary that names no other file, else the general
 * minimum. A run's minimum sat only in minSizes, and the starter drew the logo under it at the kit's 16px.
 */
export function minimumFor(logo, file) {
  const base = path.basename(String(file ?? '')).toLowerCase();
  const key = (v) => String(v ?? '').trim().toLowerCase();
  const named = new Map((logo?.variants ?? []).filter((v) => v?.name && v?.file).map((v) => [key(v.name), path.basename(v.file).toLowerCase()]));
  const sizes = (logo?.minSizes ?? []).filter((m) => typeof m?.screenPx === 'number' && m.screenPx > 0 && typeof m.variant === 'string');
  const entry = sizes.find((m) => named.get(key(m.variant)) === base) ?? sizes.find((m) => !named.has(key(m.variant)) && /\bprimary\b/i.test(m.variant));
  if (entry) return { px: entry.screenPx, from: `identity.logo.minSizes (${entry.variant})` };
  const px = logo?.minSize?.screenPx;
  return typeof px === 'number' && px > 0 ? { px, from: 'identity.logo.minSize' } : null;
}

const slugOf = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/**
 * The brand's illustration library beside the character's moments, to pick from. Which drawing marks which moment
 * is a person's pick, or the run's, recorded: a run mapped five of seventeen by hand. So nothing is guessed, and only
 * a drawing whose file name or title is a moment's own name is taken. Paths are relative to product/, as product.json
 * writes them. Null without a library, or once the character is named.
 */
export function illustrationChoices({ brand, brandRoot, productDir, character = null }) {
  const library = (brand?.identity?.illustration?.library ?? []).filter((d) => typeof d?.file === 'string' && !path.isAbsolute(d.file));
  if (!library.length || character || !brandRoot || !productDir) return null;
  // A library file's path is from the project root.
  const drawings = library.map((d) => ({ file: path.relative(productDir, path.resolve(brandRoot, d.file)), title: d.title ?? null, set: d.set ?? null }));
  const taken = {};
  for (const state of CHARACTER_STATES) {
    const d = drawings.find((x) => [slugOf(path.basename(x.file, path.extname(x.file))), slugOf(x.title)].includes(state));
    if (d) taken[state] = d.file;
  }
  const poses = CHARACTER_STATES.map((st) => `      ${JSON.stringify(st)}: ${JSON.stringify(taken[st] ?? '')}`).join(',\n');
  return { drawings, taken, block: `"brand": { "character": { "name": "[the drawings' name]", "poses": {\n${poses}\n} } }` };
}

/** A character product.json names, its pose paths read from product/, or the drawings taken by their exact names. */
function characterFrom(block, choices, productDir, brandName) {
  const fromProduct = (map) => Object.fromEntries(Object.entries(map ?? {}).map(([k, v]) => [k, path.resolve(productDir, v)]));
  if (block?.character) return { ...block.character, ...(block.character.poses ? { poses: fromProduct(block.character.poses) } : {}), ...(block.character.flat ? { flat: fromProduct(block.character.flat) } : {}) };
  if (choices && Object.keys(choices.taken).length) return { name: brandName ? `${brandName} illustrations` : 'Illustrations', poses: fromProduct(choices.taken) };
  return null;
}

/** A still's media type, from its name. */
const stillType = (file) => (/\.webp$/i.test(file) ? 'image/webp' : /\.jpe?g$/i.test(file) ? 'image/jpeg' : 'image/png');

/**
 * A pose still small enough to carry in the bundle, drawn down in headless Chrome to WebP. The canvas
 * has no public folder, so a still referenced by path shows as a broken image on every board; an
 * 800 KB character still at 320px comes back near 20 KB. Null without Chrome.
 */
export async function shrinkStill(file, { maxSide = 320, quality = 0.82, chrome = findChrome() } = {}) {
  if (!chrome) return null;
  const type = stillType(file);
  const dir = mkdtempSync(path.join(tmpdir(), 'brandi-still-'));
  try {
    const page = path.join(dir, 'still.html');
    writeFileSync(page, `<!doctype html><body><img id="i" src="data:${type};base64,${readFileSync(file).toString('base64')}"><script>
const i = document.getElementById('i');
i.decode().then(() => {
  const s = Math.min(1, ${maxSide} / Math.max(i.naturalWidth, i.naturalHeight));
  const c = document.createElement('canvas');
  c.width = Math.round(i.naturalWidth * s);
  c.height = Math.round(i.naturalHeight * s);
  c.getContext('2d').drawImage(i, 0, 0, c.width, c.height);
  document.body.setAttribute('data-still', c.toDataURL('image/webp', ${quality}));
  i.remove();
});
</script></body>`);
    const { stdout } = await run(chrome, ['--headless=new', '--disable-gpu', '--no-first-run', '--no-default-browser-check', '--virtual-time-budget=10000', '--dump-dom', pathToFileURL(page).href], { timeout: 60000, maxBuffer: 64 * 1024 * 1024 });
    return /data-still="(data:image\/webp;base64,[^"]+)"/.exec(stdout)?.[1] ?? null;
  } catch {
    return null;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

// Brandi's own brand file writes a logo's role as free text ("secondary: black logo outline reversed to white"),
// and the logo forge writes primary, mono-white and mono-black. So a role is read by its words, lower-cased, once
// any ground it names ("on black", "for dark backgrounds") is taken out, since a ground is not an ink: white,
// reversed or knocked out is the file for dark grounds; black, mono or one colour is the one ink; primary is the
// master. White is read before black, so "black logo outline reversed to white" is the dark-ground file. An exact
// role wins, then a match whose role names no ground, then one that does, and an SVG before a picture.
const ROLE_WORDS = [
  ['mono-white', /\b(mono-?white|white|reversed?|knock(ed)?[- ]?out)\b/],
  ['mono-black', /\b(mono-?black|black|mono|one[- ]colou?r|single[- ]colou?r)\b/],
  ['primary', /\bprimary\b/],
];
const GROUND = /\b(?:(?:on|for) (?:a |the )?(?:black|white|dark|light|paper)(?: (?:back)?grounds?)?|(?:black|white|dark|light) (?:back)?grounds?)\b/g;
const roleWord = (role) => {
  const words = String(role ?? '').toLowerCase().replace(GROUND, ' ');
  return ROLE_WORDS.find(([, re]) => re.test(words))?.[0] ?? null;
};
const namesGround = (role) => new RegExp(GROUND.source).test(String(role ?? '').toLowerCase());

/**
 * Where the marks come from: { from, name, files: { rendition: path }, inkFrom, logo, character, base, record }.
 * When nothing names a full logo, `files` is empty, and the kit's stand-in mark carries the brand's own name and
 * character (brandConstant). `record` is true for files brand.json names, which can be ahead of the drawing.
 *
 * brand.json's logo paths are relative to the brand folder (`brandDir`, brand/ under `brandRoot` unless given),
 * and are read from there first, then from the project root, as the brand book reads them. Read from the project
 * root alone, a route-A starter failed on its first mark.
 */
export function brandSources({ product = {}, brand = null, productDir, brandRoot, brandDir = brandRoot ? path.join(brandRoot, 'brand') : null }) {
  const block = product.brand;
  const illustrations = illustrationChoices({ brand, brandRoot, productDir, character: block?.character ?? null });
  if (block?.marks?.full) {
    return { from: 'product/product.json', name: block.name ?? product.productName ?? brand?.meta?.name ?? null, files: block.marks, inkFrom: null, logo: block.logo ?? {}, character: characterFrom(block, illustrations, productDir, brand?.meta?.name), base: productDir, notes: [], illustrations };
  }
  const files = (brand?.identity?.logo?.files ?? []).map((f) => (typeof f === 'string' ? { path: f } : f)).filter((f) => f?.path);
  const rank = (f, r) => (f.role === r ? 0 : roleWord(f.role) !== r ? null : namesGround(f.role) ? 2 : 1);
  const role = (r, ok = () => true) => files
    .map((f, i) => ({ f, i, rank: rank(f, r) }))
    .filter((c) => c.rank !== null && ok(c.f.path))
    .sort((a, b) => a.rank - b.rank || Number(!/\.svg$/i.test(a.f.path)) - Number(!/\.svg$/i.test(b.f.path)) || a.i - b.i)[0]?.f.path ?? null;
  const full = role('primary');
  if (!full) {
    return { from: files.length ? "brand/brand.json's logo master" : null, name: block?.name ?? brand?.meta?.name ?? null, files: {}, inkFrom: null, logo: {}, character: characterFrom(block, illustrations, productDir, brand?.meta?.name), base: productDir, notes: [], illustrations, record: files.length > 0 };
  }
  const rec = brand.identity.logo;
  const logo = {};
  const notes = [];
  const ratio = clearSpaceRatio(rec.clearSpace);
  if (ratio) logo.clearSpace = ratio;
  // A share of the width is read once the mark's shape is known (brandConstant).
  else if (clearSpaceRatio(rec.clearSpace, { aspect: 1 })) logo.clearSpaceWords = String(rec.clearSpace);
  const min = minimumFor(rec, full);
  if (min) logo.minLongSide = min.px;
  // product.json's brand.logo settles what the record cannot: clear space written in words, a minimum it lacks.
  const set = Object.fromEntries(Object.entries(block?.logo ?? {}).filter(([k, v]) => k in LOGO_DEFAULTS && typeof v === 'number'));
  Object.assign(logo, set);
  if (min && set.minHeight == null) notes.push(`the minimum, ${min.px}px along the long side, from ${min.from}`);
  if (logo.clearSpace == null && !logo.clearSpaceWords && rec.clearSpace) {
    notes.push(`clear space is written in words the starter cannot turn into a share of the logo's height: "${rec.clearSpace}". Set product.json "brand": { "logo": { "clearSpace": <a share of the logo's height> } }, 0.25 for a quarter of its height on every side, and run it again`);
  }
  const onDark = role('mono-white');
  return {
    from: "brand/brand.json's logo master",
    name: brand.meta?.name ?? null,
    files: { full, ...(onDark ? { 'full-on-dark': onDark } : {}) },
    // The one ink takes the text colour, which only an outline drawing can.
    inkFrom: role('mono-black', (p) => /\.svg$/i.test(p)),
    logo,
    character: characterFrom(block, illustrations, productDir, brand.meta?.name),
    base: [brandDir, brandRoot].find((d) => d && existsSync(path.resolve(d, full))) ?? brandDir ?? brandRoot,
    notes,
    illustrations,
    record: true,
  };
}

/**
 * A PNG logo as an SVG the system can draw like any other mark: the picture inside a viewBox of its own
 * size, so a lockup, a rail and an email size it by its shape. Some brands only supply the logo for a
 * screen header as a PNG.
 */
export function rasterMark(bytes, where = 'a mark') {
  const png = bytes.length > 24 && bytes.readUInt32BE(0) === 0x89504e47 && bytes.toString('ascii', 12, 16) === 'IHDR';
  if (!png) throw new Error(`${where} is not a PNG or an SVG. Export it as either.`);
  if (bytes.length > 400 * 1024) throw new Error(`${where} is ${Math.round(bytes.length / 1024)} KB. Export it at twice the largest size it is drawn at.`);
  const w = bytes.readUInt32BE(16);
  const h = bytes.readUInt32BE(20);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}"><image href="data:image/png;base64,${bytes.toString('base64')}" width="${w}" height="${h}"/></svg>`;
}

/**
 * The generated part of lib/brand.ts. A pose still comes from `stills`, drawn down; one that could not be drawn
 * down goes in at full size, as a data URI, and is named in `stills` on the result. Never a path from the page
 * root: the canvas has no public folder, so a board shows that as a broken image. Throws, naming the file, when a
 * mark product.json names is missing, or any mark is unsafe.
 *
 * With no full logo drawn, BRAND carries the kit's stand-in mark (STAND_IN_MARKS) at the kit's sizes, under the
 * brand's own name, and the file says it is not the brand's logo. Nothing is drawn or set in type for it.
 */
export function brandConstant(src, { stills = new Map() } = {}) {
  const read = (rel, what) => {
    const file = path.resolve(src.base, rel);
    if (!existsSync(file)) throw new Error(`${what}: ${rel} does not exist in ${src.base} (from ${src.from}).`);
    return { file, text: readFileSync(file, 'utf8') };
  };
  // brand.json can name a logo before anyone has drawn it: a brand stage documents the variants it will have. Such a
  // file is left out and listed, never a stop: a run met one and wrote nothing. A file product.json names is the
  // product's own pick, so one missing there still stops the starter.
  const missing = [];
  const drawn = (rel) => {
    if (!src.record || !rel || existsSync(path.resolve(src.base, rel))) return true;
    missing.push(rel);
    return false;
  };
  const files = Object.fromEntries(Object.entries(src.files ?? {}).filter(([, rel]) => drawn(rel)));
  const inkFrom = src.inkFrom && drawn(src.inkFrom) ? src.inkFrom : null;
  const standIn = !files.full;
  const marks = {};
  // Without the full logo the record's other files go unused: the marks are one set, and the stand-in is all of it.
  for (const [rendition, rel] of standIn && src.record ? [] : Object.entries(files)) {
    if (!RENDITIONS.includes(rendition)) throw new Error(`${src.from} names a mark "${rendition}"; the renditions are ${RENDITIONS.join(', ')}.`);
    if (rel && /\.png$/i.test(rel)) {
      // A picture cannot take the text colour, so an ink rendition stays an outline drawing.
      if (rendition.endsWith('-ink')) throw new Error(`${src.from}: the ${rendition} mark has to be an SVG, because an ink rendition takes the text colour and a PNG cannot.`);
      marks[rendition] = rasterMark(readFileSync(read(rel, `the ${rendition} mark`).file), rel);
      continue;
    }
    // An ink rendition is one colour by definition, so whatever its file's ink, it takes the text colour.
    if (rel) marks[rendition] = scopeClasses(tighten((rendition.endsWith('-ink') ? toInk : (x) => x)(cleanSvg(read(rel, `the ${rendition} mark`).text, rel))), `brand-${rendition}-`);
  }
  if (!standIn && inkFrom && !marks['full-ink']) marks['full-ink'] = scopeClasses(tighten(toInk(cleanSvg(read(inkFrom, 'the one-ink mark').text, inkFrom))), 'brand-full-ink-');
  // A mark much wider than tall is not a symbol, whatever it is named: without one, the icons rail shows its Home
  // control rather than a mark that overflows its square.
  const refused = [];
  const symbolAspect = marks.symbol ? aspectOf(marks.symbol) : null;
  if (symbolAspect && 1 / symbolAspect > SYMBOL_MAX_ASPECT) {
    refused.push(`the symbol (${src.files.symbol}) is ${(1 / symbolAspect).toFixed(2)} times as wide as it is tall, and a symbol fills a square place (${SYMBOL_MAX_ASPECT} at most), so it is not used as one and the icons rail shows its Home control. Name a squarer mark as the symbol, or none.`);
    for (const r of ['symbol', 'symbol-on-dark', 'symbol-ink']) delete marks[r];
  }

  const kept = [];
  // The stand-in keeps the kit's sizes: the record's minimum and clear space belong to the mark nobody has drawn yet.
  const logo = standIn ? { ...LOGO_DEFAULTS } : {};
  for (const key of standIn ? [] : Object.keys(LOGO_DEFAULTS)) {
    if (typeof src.logo?.[key] === 'number') logo[key] = src.logo[key];
  }
  // Brandi records the smallest size along the long side; the product sizes a logo by its height.
  const aspect = aspectOf(marks.full);
  if (logo.minHeight == null && src.logo?.minLongSide && aspect) logo.minHeight = Math.max(1, Math.ceil(src.logo.minLongSide * Math.min(aspect, 1)));
  if (logo.clearSpace == null && src.logo?.clearSpaceWords && aspect) {
    const share = clearSpaceRatio(src.logo.clearSpaceWords, { aspect });
    if (share) logo.clearSpace = share;
  }
  for (const [key, value] of Object.entries(LOGO_DEFAULTS)) {
    if (logo[key] != null) continue;
    // With no symbol of its own on record, the symbol's floor is the logo's, when that came from the record.
    if (key === 'symbolMinHeight' && !kept.includes('minHeight')) { logo[key] = logo.minHeight; continue; }
    logo[key] = value;
    kept.push(key);
  }
  if (logo.height < logo.minHeight) logo.height = logo.minHeight;

  let character = null;
  const full = [];
  const inkPoses = [];
  if (src.character?.poses) {
    const poses = (map) => {
      const out = {};
      for (const [state, rel] of Object.entries(map ?? {})) {
        if (!CHARACTER_STATES.includes(state)) throw new Error(`${src.from} gives the character a "${state}" pose; the states are ${CHARACTER_STATES.join(', ')}.`);
        if (/\.svg$/i.test(rel)) {
          const svg = cleanSvg(read(rel, `the ${state} pose`).text, rel);
          const ink = oneDarkInk(svg);
          if (ink && !inkPoses.includes(state)) inkPoses.push(state);
          out[state] = scopeClasses(ink ? toInk(svg) : svg, `brand-${state}-`);
          continue;
        }
        const { file } = read(rel, `the ${state} pose`);
        if (stills.has(file)) { out[state] = stills.get(file); continue; }
        if (!full.includes(file)) full.push(file);
        out[state] = `data:${stillType(file)};base64,${readFileSync(file).toString('base64')}`;
      }
      return out;
    };
    character = { name: src.character.name ?? src.name ?? 'Character', poses: poses(src.character.poses) };
    if (src.character.flat) character.flat = poses(src.character.flat);
  }

  const json = (v) => JSON.stringify(v);
  const name = src.name ?? 'Product';
  const said = missing.join(', ');
  // Written so the stand-in cannot be taken for the brand's own: a run's reviewers saw the kit's mark and name.
  const head = standIn ? [
    `${BRAND_MARKER} ${src.from ? `from ${src.from}` : 'with no logo on record'}. Add the logo's files and run it again;`,
    '// a hand edit here is undone by the next run.',
    `// Not the brand's logo. ${name} has no drawn mark yet, so BRAND carries the kit's stand-in, STAND_IN_MARKS,`,
    "// at the kit's sizes, until the brand's own files are there.",
    said ? `// Named in ${src.from} and not drawn yet: ${said}.` : null,
    character ? null : `// ${name} has no character, so Character draws nothing.`,
  ] : [
    `${BRAND_MARKER} from ${src.from}. Change the files there and run it again;`,
    '// a hand edit here is undone by the next run.',
    said ? `// Not drawn yet, so left out: ${said}.` : null,
    kept.length ? `// The record holds no ${kept.join(', ')}, so ${kept.length === 1 ? 'it keeps the kit default' : 'they keep the kit defaults'} until it does.` : null,
  ];
  const lines = [
    ...head,
    ...refused.map((r) => `// Not a symbol: ${r}`),
    inkPoses.length ? `// Drawn in one dark ink, so they take the text colour on any ground: ${inkPoses.join(', ')}.` : null,
    '',
    'export const BRAND: Brand = {',
    `  name: ${json(name)},`,
    ...(standIn ? ['  marks: STAND_IN_MARKS,'] : ['  marks: {', ...Object.entries(marks).map(([k, v]) => `    ${json(k)}: ${json(v)},`), '  },']),
    `  logo: { height: ${logo.height}, minHeight: ${logo.minHeight}, symbolMinHeight: ${logo.symbolMinHeight}, clearSpace: ${Number(logo.clearSpace.toFixed(3))} },`,
  ].filter((l) => l !== null);
  if (character) {
    lines.push('  character: {', `    name: ${json(character.name)},`, '    poses: {', ...Object.entries(character.poses).map(([k, v]) => `      ${json(k)}: ${json(v)},`), '    },');
    if (character.flat) lines.push('    flat: {', ...Object.entries(character.flat).map(([k, v]) => `      ${json(k)}: ${json(v)},`), '    },');
    lines.push('  },');
  }
  lines.push('}', '');
  return { source: lines.join('\n'), kept, marks: Object.keys(marks), stills: full.map((f) => path.basename(f)), character: Boolean(character), refused, inkPoses, placeholder: standIn, missing };
}

/**
 * The whole file: the types from the current lib/brand.ts, then the brand's constant. Null when the
 * file has neither the placeholder nor the generated marker, because then it is the product's own.
 */
export function brandModule(current, generated) {
  const at = [PLACEHOLDER, BRAND_MARKER].map((m) => current.indexOf(`\n${m}`)).filter((i) => i >= 0);
  if (!at.length) return null;
  return `${current.slice(0, Math.min(...at) + 1)}${generated}`;
}

export default { shrinkStill, rasterMark, cleanSvg, inlineClassStyles, tighten, scopeClasses, toInk, oneDarkInk, clearSpaceRatio, minimumFor, illustrationChoices, brandSources, brandConstant, brandModule, RENDITIONS, CHARACTER_STATES, LOGO_DEFAULTS, BRAND_MARKER, SYMBOL_MAX_ASPECT };
