/**
 * Brandi product layer: PRODUCT.md and DESIGN.md, Impeccable's context files, written from the system.
 *
 * PRODUCT.md carries the intake in product/product.json: who uses each surface and for what, the
 * systems each reads and writes and how they fail, what the assistant may do, the market and the
 * accessibility target. DESIGN.md records what the tokens and the definitions ship, in the DESIGN.md
 * format Impeccable reads: tokens in the YAML frontmatter, then its canonical sections in order.
 *
 * Neither file owns a value. Both are rewritten from the system on every `brandi product starter`,
 * and a file without the marker (one a person or Impeccable has taken over) is left alone.
 */

import { GROUPS, DESIGN_PROPS } from './productdocs.mjs';

export const CONTEXT_MARKER = '<!-- generated by brandi product starter from the system: change product/product.json or the tokens, then run it again -->';
export const PRODUCT_SCHEMA = '<!-- impeccable:product-schema 1 -->';

const list = (xs) => {
  const a = (xs ?? []).filter(Boolean);
  return a.length < 2 ? (a[0] ?? '') : `${a.slice(0, -1).join(', ')} and ${a.at(-1)}`;
};

/** Impeccable's platform value from the surfaces' platforms: web, ios, android or adaptive. */
export function impeccablePlatform(platforms = []) {
  const p = new Set(platforms.map((x) => String(x).toLowerCase()));
  const ios = ['ios', 'ipados', 'ios-ipados'].some((k) => p.has(k));
  const android = p.has('android');
  const other = [...p].some((k) => !['ios', 'ipados', 'ios-ipados', 'android'].includes(k));
  if (ios && !android && !other) return 'ios';
  if (android && !ios && !other) return 'android';
  return ios || android ? 'adaptive' : 'web';
}

/** PRODUCT.md from product.json. A field the intake has not answered is a bracketed gap, never prose. */
export function productMd({ product = {}, identity, brandName = null }) {
  const out = ['# Product', '', PRODUCT_SCHEMA, ''];
  const section = (title, body) => { if (body && body.trim()) out.push(`## ${title}`, '', body.trim(), ''); };
  const surfaces = product.surfaces ?? [];
  section('Platform', impeccablePlatform([...(product.platforms ?? []), ...surfaces.flatMap((s) => s.platforms ?? [])]));
  section('Users', surfaces.map((s) =>
    `- ${s.people ?? '[who uses it]'}, on the ${s.name}${s.platforms?.length ? ` (${s.platforms.join(', ')})` : ''}: ${s.jobs ?? '[what they do there]'}.`).join('\n'));
  section('Product Purpose', product.purpose);
  section('Positioning', product.positioning);
  section('Operating Context', (product.systems ?? []).map((s) => {
    const io = [s.reads && `reads ${s.reads}`, s.writes && `writes ${s.writes}`].filter(Boolean).join(', ');
    const fails = s.fails?.length ? ` Failure modes: ${s.fails.join('; ')}. Each is a state on a states board, and the copy names ${s.name}.` : '';
    return `- ${s.name}${io ? `: ${io}.` : '.'}${fails}`;
  }).join('\n'));
  const caps = [];
  const a = product.assistant;
  if (a?.drafts?.length) caps.push(`The assistant drafts ${list(a.drafts)}. A person sends.`);
  if (a?.approves) caps.push(`A person approves ${a.approves}.`);
  if (a?.never?.length) caps.push(`The assistant never ${list(a.never)}.`);
  caps.push(`Numbers, dates and money are formatted for ${identity.locale} in ${identity.currency}, by lib/format.js in both builds.`);
  for (const q of product.openQuestions ?? product.open ?? []) {
    caps.push(`Undecided: ${q.question ?? q}${q.assumed ? ` Working assumption: ${q.assumed}` : ''}`);
  }
  section('Capabilities and Constraints', caps.map((c) => `- ${c}`).join('\n'));
  section('Brand Commitments', [
    `- Name: ${identity.name}${brandName && brandName !== identity.name ? `, under the ${brandName} brand` : ''}.`,
    '- DESIGN.md records the visual system and system/tokens.json owns it. A value changes in the tokens and arrives through the generator.',
    product.voice ? `- Voice: ${product.voice}` : null,
  ].filter(Boolean).join('\n'));
  section('Evidence on Hand', product.evidence);
  section('Accessibility & Inclusion', product.accessibility
    ?? 'WCAG 2.2 AA on every route and state, checked by axe, and the behaviour checks every component carries: keyboard, touch, reduced motion and forced colours, in light and dark.');
  out.push(CONTEXT_MARKER, '');
  return out.join('\n');
}

const yamlKey = (k) => (/^[A-Za-z_][A-Za-z0-9_.-]*$/.test(k) ? k : JSON.stringify(k));
const yamlValue = (v) => (typeof v === 'number' ? String(v) : JSON.stringify(String(v)));
function yaml(obj, indent = '') {
  return Object.entries(obj)
    .filter(([, v]) => v !== undefined && v !== null && !(typeof v === 'object' && !Object.keys(v).length))
    .map(([k, v]) => (typeof v === 'object' ? `${indent}${yamlKey(k)}:\n${yaml(v, `${indent}  `)}` : `${indent}${yamlKey(k)}: ${yamlValue(v)}`))
    .join('\n');
}

const rawOf = (t, theme) => (t.value && typeof t.value === 'object' ? t.value[theme] : t.value);

// The order colour families are described in. A role joins the first family whose test it passes.
const FAMILIES = [
  ['Action', (n) => /^(primary|on-primary|link|focus|hover|pressed|selected)/.test(n)],
  ['Brand', (n) => /^(brand|on-brand)/.test(n)],
  ['Surfaces', (n) => /^(canvas|surface|scrim)/.test(n)],
  ['Text', (n) => /^text/.test(n)],
  ['Lines', (n) => /^line/.test(n)],
  ['Rail', (n) => /^rail/.test(n)],
  ['Status', (n) => /^(success|warning|danger|info|on-danger)/.test(n)],
  ['Assistant', (n) => /^ai/.test(n)],
  ['Highlight', (n) => /highlight/.test(n)],
  ['Data', (n) => /^(series|chart)/.test(n)],
  ['Tags', (n) => /^tag/.test(n)],
];

/** DESIGN.md from the tokens and the component definitions. */
export function designMd({ tokens, identity, defs = [], brandName = null }) {
  const colours = tokens.color?.tokens ?? [];
  // A role can alias another ("{surface}"). DESIGN.md wants the value itself: primitives never refer to each other.
  const byName = new Map(colours.map((t) => [t.name, t]));
  const valueOf = (t, theme = 'light', seen = new Set()) => {
    const v = rawOf(t, theme);
    const alias = typeof v === 'string' && /^\{([a-z0-9-]+)\}$/.exec(v);
    if (!alias || seen.has(t.name) || !byName.has(alias[1])) return v;
    return valueOf(byName.get(alias[1]), theme, new Set([...seen, t.name]));
  };
  const families = tokens.type?.families ?? {};
  const styles = (tokens.type?.groups ?? []).flatMap((g) => g.styles.map((s) => ({ ...s, group: g })));
  const scale = (key) => tokens[key]?.tokens ?? [];
  const has = { colors: new Set(colours.map((t) => t.name)), typography: new Set(styles.map((s) => s.name)), rounded: new Set(scale('radius').map((t) => t.name)) };

  const components = {};
  for (const d of defs) {
    for (const [row, props] of Object.entries(d.design ?? {})) {
      const entry = {};
      for (const [prop, v] of Object.entries(props)) {
        const kind = prop === 'backgroundColor' || prop === 'textColor' ? 'colors' : prop === 'typography' ? 'typography' : prop === 'rounded' ? 'rounded' : null;
        if (kind && has[kind].has(v)) entry[prop] = `{${kind}.${v}}`;
        else if (!kind) entry[prop] = v;
      }
      components[row] = entry;
    }
  }
  const front = yaml({
    name: identity.name,
    description: `The ${brandName ?? identity.name} product system: roles, type, shape and components, from system/tokens.json.`,
    colors: Object.fromEntries(colours.map((t) => [t.name, valueOf(t)])),
    typography: Object.fromEntries(styles.map((s) => [s.name, {
      fontFamily: families[s.group.family] ?? s.group.family, fontSize: s.fontSize, fontWeight: s.fontWeight, lineHeight: s.lineHeight, letterSpacing: s.letterSpacing,
    }])),
    rounded: Object.fromEntries(scale('radius').map((t) => [t.name, valueOf(t)])),
    spacing: Object.fromEntries(scale('spacing').map((t) => [t.name, valueOf(t)])),
    components,
  });

  const out = ['---', front, '---', '', `# Design System: ${identity.name}`, ''];
  out.push('## Overview', '',
    `${identity.name} is the product system${brandName && brandName !== identity.name ? ` for ${brandName}` : ''}: ${colours.length} colour roles, each with a light and a dark value, ${styles.length} type styles, and ${defs.length} components, each with its definition in components/system. The values live in system/tokens.json. This file records them and owns none of them.`, '');

  out.push('## Colors', '');
  const placed = new Set();
  for (const [family, test] of FAMILIES) {
    const members = colours.filter((t) => !placed.has(t.name) && test(t.name));
    if (!members.length) continue;
    out.push(`### ${family}`, '');
    for (const t of members) {
      placed.add(t.name);
      const dark = valueOf(t, 'dark');
      out.push(`- \`${t.name}\` ${valueOf(t)}${dark && dark !== valueOf(t) ? `, dark ${dark}` : ''}${t.usage ? `. ${t.usage.trim().replace(/\.$/, '')}.` : ''}`);
    }
    out.push('');
  }
  const rest = colours.filter((t) => !placed.has(t.name));
  if (rest.length) out.push('### Other', '', ...rest.map((t) => `- \`${t.name}\` ${valueOf(t)}`), '');

  out.push('## Typography', '');
  for (const [role, stack] of Object.entries(families)) out.push(`- ${role}: ${stack}`);
  out.push('');
  for (const g of tokens.type?.groups ?? []) {
    out.push(`### ${g.name}`, '');
    if (g.note) out.push(g.note.trim(), '');
    for (const s of g.styles) out.push(`- \`${s.name}\` ${s.fontSize}/${s.lineHeight}, weight ${s.fontWeight}${s.letterSpacing && s.letterSpacing !== 'normal' ? `, tracking ${s.letterSpacing}` : ''}${s.usage ? `. ${s.usage.trim().replace(/\.$/, '')}.` : ''}`);
    out.push('');
  }

  out.push('## Layout', '',
    `Spacing: ${scale('spacing').map((t) => `${t.name} ${valueOf(t)}`).join(', ')}.`, '');
  if (scale('breakpoint').length) out.push(`Breakpoints: ${scale('breakpoint').map((t) => `${t.name} ${valueOf(t)}`).join(', ')}.`, '');
  out.push('Every screen is checked at 1440, 820 and 390 pixels wide, in light and dark.', '');

  if (scale('shadow').length) {
    out.push('## Elevation & Depth', '');
    if (tokens.shadow.note) out.push(tokens.shadow.note.trim(), '');
    for (const t of scale('shadow')) out.push(`- \`${t.name}\` ${valueOf(t)}${valueOf(t, 'dark') && valueOf(t, 'dark') !== valueOf(t) ? `; dark ${valueOf(t, 'dark')}` : ''}`);
    out.push('');
  }

  out.push('## Shapes', '');
  if (tokens.radius?.note) out.push(tokens.radius.note.trim(), '');
  for (const t of scale('radius')) out.push(`- \`${t.name}\` ${valueOf(t)}${t.usage ? `. ${t.usage.trim().replace(/\.$/, '')}.` : ''}`);
  out.push('');

  if (defs.length) {
    out.push('## Components', '');
    for (const group of GROUPS) {
      const members = defs.filter((d) => d.group === group);
      if (!members.length) continue;
      out.push(`### ${group}`, '', ...members.map((d) => `- **${d.name}**${d.status === 'to build' ? ' (to build)' : ''}: ${d.job.trim()}`), '');
    }
  }

  out.push("## Do's and Don'ts", '', '### Do:', '',
    '- Use colour through its role, as var(--role) or the Tailwind utility. The drift check reports a raw value typed where a role exists.',
    '- Format every number, date and amount with lib/format.js, so the canvas and the product agree.',
    '- Keep the focus outline on everything a person can press or type into.',
    '', "### Don't:", '',
    '- Change a value here first. Change system/tokens.json and run brandi product starter.',
    '- Restyle a component for one screen. Change its definition and the component, or add a variant.',
    '');
  out.push(CONTEXT_MARKER, '');
  return out.join('\n');
}

export default { productMd, designMd, impeccablePlatform, CONTEXT_MARKER, PRODUCT_SCHEMA };
