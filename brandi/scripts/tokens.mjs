/**
 * Brandi token emitters.
 *
 * One resolved design system in, four artefacts out:
 *   tokens.json    Design Tokens Community Group (DTCG) format
 *   tokens.css     custom properties, three tiers, light and dark
 *   tailwind.css   a Tailwind v4 @theme block
 *   tokens.ts      a typed TypeScript module
 *
 * DTCG is a Design Tokens Community Group Report, NOT a W3C standard and not on
 * the W3C Standards Track. The current draft (Format Module 2025.10) carries the
 * line "Do not attempt to implement this version." So this emitter targets the
 * shape the ecosystem actually reads, states every divergence in
 * references/10-implementation.md, and calls the output DTCG rather than
 * implying a standard that does not exist.
 * https://tr.designtokens.org/format/
 *
 * The format has also changed shape: `dimension` was a string
 * ("16px") in early drafts and became an object ({value: 16, unit: "px"}) in
 * the 2024 revision. Style Dictionary and most tooling in the wild still read
 * the string form, so `dimensionStyle` lets a caller pick. The default follows
 * the current spec; pass 'string' when feeding an older pipeline.
 * https://tr.designtokens.org/format/
 */

import { resolveToken } from './system.mjs';

const DTCG_SCHEMA = 'https://tr.designtokens.org/format/';
const DTCG_STATUS =
  'Design Tokens Community Group Report format. This is a Community Group Report, ' +
  'not a W3C standard, and the draft is still changing. Check what your build tool ' +
  'actually reads before wiring this in.';

function dim(px, style) {
  if (style === 'string') return `${px}px`;
  return { value: px, unit: 'px' };
}

/** Escape a string for safe inclusion in a CSS comment. */
const cssComment = (s) => String(s).replace(/\*\//g, '*\\/');

/** A CSS custom property name from a dotted token path. */
export const cssVar = (path) => `--${path.replace(/\./g, '-')}`;

