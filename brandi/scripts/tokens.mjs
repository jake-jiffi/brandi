/**
 * A Tailwind v4 `@theme` block. v4 reads design tokens straight from CSS custom
 * properties inside `@theme`, so there is no JS config to keep in sync.
 * https://tailwindcss.com/docs/theme
 */
export function toTailwind(system, { importTokens = './tokens.css' } = {}) {
  const L = [];
  L.push('/* Tailwind v4 theme, generated by Brandi. Edit the brand file, not this. */');
  L.push('/*');
  L.push(' * Every entry below resolves through tokens.css, which is imported first, so');
  L.push(' * a Tailwind utility and a hand-written rule always land on the same value.');
  L.push(' * The names are namespaced (--color-*, --text-*, --spacing-*) because that is');
  L.push(' * what Tailwind reads; the underlying custom properties keep their own names,');
  L.push(' * so nothing here is self-referential and import order does not matter.');
  L.push(' */');
  if (importTokens) L.push(`@import "${importTokens}";`);
  L.push('@import "tailwindcss";');
  L.push('');
  L.push('@theme {');
  L.push('  /* Semantic colours. These are the ones to use: bg-surface-page, text-text-primary. */');
  for (const key of Object.keys(system.semantic.light)) {
    const name = key.replace(/\./g, '-');
    L.push(`  --color-${name}: var(--${name});`);
  }
  L.push('');
  L.push('  /* Ramps, for the rare case a semantic token genuinely does not exist yet. */');
  for (const [family, pal] of Object.entries({ ...system.palettes, ...system.status })) {
    // Already namespaced --color-* in tokens.css, so these would be self-referential.
    // Emitted as literals instead, which is also what makes them theme-stable:
    // a utility built from a ramp step means that step, not "whatever the theme says".
    for (const s of pal.light.steps) L.push(`  --color-${family}-${s.step}: ${s.hex};`);
  }
  L.push('');
  L.push('  /* Type. The custom properties in tokens.css are --text-* and --font-*,');
  L.push('     which is the same namespace Tailwind uses, so these carry the values. */');
  for (const s of system.type.scale.steps) L.push(`  --text-${s.name}: ${s.clamp ?? `${s.rem}rem`};`);
  for (const [role, family] of Object.entries(system.type.fonts)) {
    if (family) L.push(`  --font-${role}: ${Array.isArray(family) ? family.join(', ') : family};`);
  }
  L.push('');
  L.push('  /* Space. tokens.css calls these --space-*, Tailwind wants --spacing-*,');
  L.push('     so this is a genuine alias rather than a self-reference. */');
  for (const s of system.space) L.push(`  --spacing-${s.name}: var(--space-${s.name});`);
  L.push('');
  L.push('  /* Radius and elevation share their namespace with tokens.css, so they carry values. */');
  for (const r of system.radius) L.push(`  --radius-${r.name}: ${r.px === 9999 ? '9999px' : `${r.px}px`};`);
  L.push('');
  for (const e of system.elevation) L.push(`  --shadow-${e.name}: ${e.value};`);
  L.push('');
  L.push('  /* Weights, the same three the font request actually downloads. */');
  for (const w of system.type.weights) L.push(`  --font-weight-${w.name}: ${w.value};`);
  L.push('');
  L.push('  /* Tailwind v4 builds its responsive variants from --breakpoint-*. */');
  for (const b of system.layout.breakpoints) L.push(`  --breakpoint-${b.name}: ${b.px}px;`);
  L.push('}');
  L.push('');
  return L.join('\n');
}

