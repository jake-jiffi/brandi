/**
 * Emit CSS custom properties.
 *
 * Light and dark are genuinely different scales, not the same colours
 * rearranged: a dark surface is not an inverted light one, and the chroma that
 * reads as confident on white reads as radioactive on near-black. So the
 * primitive ramps are re-declared per theme, the way Radix Colors does it,
 * rather than duplicated into `-light` and `-dark` names. The semantic layer is
 * declared per theme too, which is what lets a role point at a DIFFERENT step
 * in each theme (a raised surface sits on step 1 in light and step 2 in dark).
 *
 * The tier boundary is still the load-bearing part: components consume semantic
 * tokens and never learn which theme is active.
 */
export function toCss(system, {
  prefix = '',
  darkSelector = '[data-theme="dark"]',
  includeSystemPreference = true,
  colorFormat = 'hex',
} = {}) {
  const p = prefix ? `${prefix}-` : '';
  const L = [];
  const val = (step) => (colorFormat === 'oklch' ? step.oklch : step.hex);
  const families = { ...system.palettes, ...system.status };

  L.push('/*');
  L.push(' * Design tokens. Generated by Brandi. Edit the brand file, not this.');
  L.push(' *');
  L.push(' * Three layers:');
  L.push(' *   :root primitives   raw values. Identical in every theme. Do not consume directly.');
  L.push(' *   :root semantic     what a value is FOR. Consume these.');
  L.push(' *   dark selector     the same semantic keys pointing at different primitives.');
  L.push(' *');
  L.push(' * If you find yourself writing var(--color-brand-9) in a component, the');
  L.push(' * semantic layer is missing a token. Add one there instead.');
  L.push(' */');
  L.push('');

  const primitives = (mode, indent) => {
    const out = [];
    out.push(`${indent}/* Colour ramps */`);
    for (const [family, pal] of Object.entries(families)) {
      for (const st of pal[mode].steps) {
        out.push(`${indent}--${p}color-${family}-${st.step}: ${val(st)}; /* ${cssComment(st.role)} */`);
      }
    }
    return out;
  };

  const semanticBlock = (flat, indent) =>
    Object.entries(flat).map(([key, value]) => {
      const resolved = typeof value === 'string' && value.startsWith('{')
        ? `var(--${p}color-${value.slice(1, -1).split('.').slice(1).join('-')})`
        : value;
      return `${indent}--${p}${key.replace(/\./g, '-')}: ${resolved};`;
    });

  // --- Light: primitives, then the semantic layer over them --------------
  L.push(':root {');
  L.push('  color-scheme: light;');
  L.push(...primitives('light', '  '));
  L.push('');
  L.push('  /* Spacing */');
  for (const st of system.space) L.push(`  --${p}space-${st.name}: ${st.px === 0 ? '0' : `${st.rem}rem`};`);
  L.push('');
  L.push('  /* Radius */');
  for (const r of system.radius) L.push(`  --${p}radius-${r.name}: ${r.px === 9999 ? '9999px' : `${r.px}px`};`);
  L.push('');
  L.push('  /* Chart colour. Not the brand ramps: those are built for hierarchy,');
  L.push('     these are checked to stay apart under colour-blindness. */');
  system.dataViz.categorical.forEach((hex, i) => L.push(`  --${p}chart-${i + 1}: ${hex};`));
  system.dataViz.sequential.forEach((hex, i) => L.push(`  --${p}chart-seq-${i + 1}: ${hex};`));
  L.push('');
  L.push('  /* Layout. A custom property cannot be used inside a media query, so');
  L.push('     these are the numbers to type into one, not values to reference');
  L.push('     there. --content-max IS usable, and is what a text column wants. */');
  for (const b of system.layout.breakpoints) L.push(`  --${p}bp-${b.name}: ${b.px}px;  /* ${b.use} */`);
  L.push(`  --${p}content-max: ${system.layout.contentMaxPx}px;`);
  L.push(`  --${p}gutter: ${system.layout.gutterPx}px;`);
  L.push('');
  L.push('  /* Type */');
  for (const w of system.type.weights) L.push(`  --${p}font-weight-${w.name}: ${w.value};  /* ${w.use} */`);
  for (const [role, family] of Object.entries(system.type.fonts)) {
    if (family) L.push(`  --${p}font-${role}: ${Array.isArray(family) ? family.join(', ') : family};`);
  }
  for (const st of system.type.scale.steps) {
    L.push(`  --${p}text-${st.name}: ${st.clamp ?? `${st.rem}rem`};`);
    L.push(`  --${p}leading-${st.name}: ${st.lineHeight};`);
    L.push(`  --${p}tracking-${st.name}: ${st.letterSpacing};`);
  }
  L.push(`  --${p}measure: ${system.type.measure.css};`);
  L.push('');
  L.push('  /* Elevation */');
  for (const e of system.elevation) L.push(`  --${p}shadow-${e.name}: ${e.value};`);
  L.push('');
  L.push('  /* Focus */');
  L.push(`  --${p}focus-ring-width: ${system.focus.widthPx}px;`);
  L.push(`  --${p}focus-ring-offset: ${system.focus.offsetPx}px;`);
  L.push('');
  L.push('  /* Motion */');
  for (const d of system.motion.durations) L.push(`  --${p}duration-${d.name}: ${d.ms}ms;`);
  for (const [name, e] of Object.entries(system.motion.easings)) L.push(`  --${p}ease-${name}: ${e.value};`);
  L.push('');
  L.push('  /* Tier 2. These are the tokens components use. */');
  L.push(...semanticBlock(system.semantic.light, '  '));
  L.push('}');
  L.push('');

  // --- Dark: the same keys, re-pointed -----------------------------------
  const darkBody = (indent) => [
    `${indent}color-scheme: dark;`,
    ...primitives('dark', indent),
    '',
    `${indent}/* Tier 2, dark. Same keys. Some point at a different step on purpose. */`,
    ...semanticBlock(system.semantic.dark, indent),
  ];

  L.push(`${darkSelector} {`);
  L.push(...darkBody('  '));
  L.push('}');
  L.push('');

  if (includeSystemPreference) {
    L.push('/* Readers who have expressed a preference but not toggled anything. */');
    L.push('@media (prefers-color-scheme: dark) {');
    L.push('  :root:not([data-theme="light"]) {');
    L.push(...darkBody('    '));
    L.push('  }');
    L.push('}');
    L.push('');
  }

  L.push('/* Honour the reader\'s setting rather than overriding it. WCAG 2.2 2.3.3 is');
  L.push('   Level AAA, so this is a house rule rather than an AA requirement, and it is');
  L.push('   one worth keeping. */');
  L.push('@media (prefers-reduced-motion: reduce) {');
  L.push('  *, *::before, *::after {');
  L.push('    animation-duration: 0.01ms !important;');
  L.push('    animation-iteration-count: 1 !important;');
  L.push('    transition-duration: 0.01ms !important;');
  L.push('    scroll-behavior: auto !important;');
  L.push('  }');
  L.push('}');
  L.push('');
  L.push('/* A focus indicator that is actually visible: WCAG 2.2 2.4.7 Focus Visible,');
  L.push('   at the 3:1 contrast 1.4.11 Non-text Contrast requires. (2.4.11 is Focus');
  L.push('   Not Obscured, which is a different thing.) */');
  L.push(':where(a, button, input, select, textarea, summary, [tabindex]):focus-visible {');
  L.push(`  outline: var(--${p}focus-ring-width) solid var(--${p}focus-ring);`);
  L.push(`  outline-offset: var(--${p}focus-ring-offset);`);
  L.push('}');
  L.push('');

  return L.join('\n');
}

