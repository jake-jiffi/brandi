// DTCG
// ---------------------------------------------------------------------------

/**
 * Emit DTCG tokens.
 *
 * Structure follows the three tiers. Tier 1 lives under `color`, `space`,
 * `radius`, `font`, `duration` and so on. Tier 2 lives under `semantic`, and
 * every entry there is an alias, which is what makes theming a swap rather
 * than a rewrite. Dark mode is emitted as a sibling `semantic-dark` group
 * rather than a `$extensions` block, because the spec has no theming primitive
 * yet and a sibling group is the shape every build tool already understands.
 */
export function toDtcg(system, { dimensionStyle = 'object', includeDark = true, letterSpacingUnit = 'em' } = {}) {
  if (!['em', 'rem'].includes(letterSpacingUnit)) {
    throw new TypeError(`letterSpacingUnit must be "em" or "rem", got ${letterSpacingUnit}`);
  }
  const out = {
    $schema: DTCG_SCHEMA,
    $description:
      DTCG_STATUS + ' ' +
      'Design tokens generated by Brandi. Tier 1 (color, space, radius, font, ' +
      'duration, easing, shadow) holds primitives and never changes between themes. ' +
      'Tier 2 (semantic) holds aliases and is the only tier a theme swaps. ' +
      'Consume tier 2. Reaching past it into tier 1 is how a design system dies.',
  };

  // --- Tier 1: colour ----------------------------------------------------
  const color = { $type: 'color' };
  const families = { ...system.palettes, ...system.status };
  for (const [family, pal] of Object.entries(families)) {
    const group = {
      $description: `${family} ramp. Step 9 is the colour itself; 1-8 are surfaces and borders, 11-12 are text.`,
    };
    pal.light.steps.forEach((s) => {
      group[String(s.step)] = {
        $value: s.hex,
        $description: `${s.role}: ${s.use}`,
      };
    });
    if (includeDark) {
      const darkGroup = { $description: `${family} ramp, dark theme.` };
      pal.dark.steps.forEach((s) => {
        darkGroup[String(s.step)] = { $value: s.hex, $description: `${s.role}: ${s.use}` };
      });
      color[`${family}-dark`] = darkGroup;
    }
    color[family] = group;
  }
  out.color = color;

  // --- Tier 1: dimension -------------------------------------------------
  out.space = { $type: 'dimension', $description: 'Spacing scale, named by pixel value.' };
  for (const s of system.space) out.space[s.name] = { $value: dim(s.px, dimensionStyle) };

  out.radius = { $type: 'dimension', $description: `Corner radius. Stance: ${system.meta.shape}.` };
  for (const r of system.radius) out.radius[r.name] = { $value: dim(r.px, dimensionStyle) };

  out.breakpoint = { $type: 'dimension', $description: system.layout.note };
  for (const b of system.layout.breakpoints) out.breakpoint[b.name] = { $value: dim(b.px, dimensionStyle), $description: b.use };

  out.layout = { $type: 'dimension', $description: 'Content column and gutter, derived from the measure.' };
  out.layout['content-max'] = { $value: dim(system.layout.contentMaxPx, dimensionStyle), $description: 'The widest a single text column should ever be.' };
  out.layout.gutter = { $value: dim(system.layout.gutterPx, dimensionStyle) };

  // --- Tier 1: typography ------------------------------------------------
  out.font = {
    family: {
      $type: 'fontFamily',
      ...Object.fromEntries(
        Object.entries(system.type.fonts)
          .filter(([, v]) => v)
          .map(([role, family]) => [role, { $value: Array.isArray(family) ? family : [family] }]),
      ),
    },
    size: {
      $type: 'dimension',
      ...Object.fromEntries(system.type.scale.steps.map((s) => [s.name, { $value: dim(s.px, dimensionStyle), $description: s.use }])),
    },
    lineHeight: {
      $type: 'number',
      ...Object.fromEntries(system.type.scale.steps.map((s) => [s.name, { $value: s.lineHeight }])),
    },
    letterSpacing: {
      $type: 'dimension',
      // The DTCG dimension type permits px and rem only, and letter spacing
      // belongs in em: it has to scale with the size it is applied to, which is
      // the whole point of tracking. `em` is therefore the default and a strict
      // validator will flag it. `rem` converts at the step's own minimum size,
      // which is exact for a fixed scale and an approximation for a fluid one,
      // and that trade is stated in the token's description rather than hidden.
      ...Object.fromEntries(
        system.type.scale.steps.map((s) => {
          const em = Number(s.letterSpacing.replace('em', ''));
          if (letterSpacingUnit === 'rem') {
            const rem = Number(((em * s.px) / system.type.scale.rootPx).toFixed(5));
            return [s.name, {
              $value: dimensionStyle === 'string' ? `${rem}rem` : { value: rem, unit: 'rem' },
              $description: `Converted from ${s.letterSpacing} at ${s.px}px for spec conformance. Exact at that size only; use the em value for a fluid scale.`,
            }];
          }
          return [s.name, {
            $value: dimensionStyle === 'string' ? s.letterSpacing : { value: em, unit: 'em' },
          }];
        }),
      ),
    },
  };

  // Composite typography tokens: one token per step, ready to apply whole.
  out.typography = { $type: 'typography' };
  const bodyRef = system.type.fonts.body ? '{font.family.body}' : null;
  for (const s of system.type.scale.steps) {
    out.typography[s.name] = {
      $value: {
        ...(bodyRef ? { fontFamily: bodyRef } : {}),
        fontSize: `{font.size.${s.name}}`,
        lineHeight: `{font.lineHeight.${s.name}}`,
        letterSpacing: `{font.letterSpacing.${s.name}}`,
      },
      $description: s.use,
    };
  }

  out.chart = { $type: 'color', $description: system.dataViz.note };
  system.dataViz.categorical.forEach((hex, i) => { out.chart[`categorical-${i + 1}`] = { $value: hex }; });
  system.dataViz.sequential.forEach((hex, i) => { out.chart[`sequential-${i + 1}`] = { $value: hex }; });

  out.fontWeight = { $type: 'fontWeight', $description: 'The three weights the font request downloads. A weight that is not loaded is a weight the browser fakes.' };
  for (const w of system.type.weights) out.fontWeight[w.name] = { $value: w.value, $description: w.use };

  // --- Tier 1: motion and elevation --------------------------------------
  out.duration = { $type: 'duration' };
  for (const d of system.motion.durations) {
    out.duration[d.name] = {
      $value: dimensionStyle === 'string' ? `${d.ms}ms` : { value: d.ms, unit: 'ms' },
      $description: d.use,
    };
  }
  out.easing = { $type: 'cubicBezier' };
  for (const [name, e] of Object.entries(system.motion.easings)) {
    const nums = e.value.match(/-?[\d.]+/g).map(Number);
    out.easing[name] = { $value: nums, $description: e.use };
  }

  out.shadow = { $type: 'shadow', $description: 'Elevation. Tinted with the brand hue, never pure black.' };
  for (const e of system.elevation) {
    // The spec's shadow type is a structured object; these are authored as CSS
    // strings because they are multi-layer and hue-tinted. Kept as a string
    // with an explicit type override so tooling does not mis-parse them.
    out.shadow[e.name] = { $type: 'string', $value: e.value, $description: e.use };
  }

  // --- Tier 2: semantic --------------------------------------------------
  const toGroup = (flat) => {
    const g = {};
    for (const [key, value] of Object.entries(flat)) {
      const [head, ...rest] = key.split('.');
      g[head] ??= { $type: 'color' };
      g[head][rest.join('.')] = { $value: value };
    }
    return g;
  };
  out.semantic = { $description: 'Tier 2. Consume these. Aliases resolve into tier 1.', ...toGroup(system.semantic.light) };
  if (includeDark) {
    const darkFlat = Object.fromEntries(
      Object.entries(system.semantic.dark).map(([k, v]) => [k, typeof v === 'string' && v.startsWith('{') ? v.replace('{color.', '{color.').replace(/^\{color\.([a-z0-9]+)\./i, '{color.$1-dark.') : v]),
    );
    out['semantic-dark'] = { $description: 'Tier 2, dark theme. Same keys, different primitives.', ...toGroup(darkFlat) };
  }

  return out;
}

