/** A typed module, for anything that needs token values in JS rather than CSS. */
export function toTypeScript(system) {
  const semantic = Object.fromEntries(
    Object.entries(system.semantic.light).map(([k, v]) => [k, resolveToken(v, system, 'light')]),
  );
  const semanticDark = Object.fromEntries(
    Object.entries(system.semantic.dark).map(([k, v]) => [k, resolveToken(v, system, 'dark')]),
  );
  const body = {
    color: Object.fromEntries(
      Object.entries({ ...system.palettes, ...system.status }).map(([f, pal]) => [
        f,
        {
          light: Object.fromEntries(pal.light.steps.map((s) => [s.step, s.hex])),
          dark: Object.fromEntries(pal.dark.steps.map((s) => [s.step, s.hex])),
        },
      ]),
    ),
    semantic: { light: semantic, dark: semanticDark },
    space: Object.fromEntries(system.space.map((s) => [s.name, s.px])),
    radius: Object.fromEntries(system.radius.map((r) => [r.name, r.px])),
    text: Object.fromEntries(system.type.scale.steps.map((s) => [s.name, { size: s.clamp ?? `${s.rem}rem`, lineHeight: s.lineHeight, letterSpacing: s.letterSpacing }])),
    font: system.type.fonts,
    fontWeight: Object.fromEntries(system.type.weights.map((w) => [w.name, w.value])),
    shadow: Object.fromEntries(system.elevation.map((e) => [e.name, e.value])),
    chart: { categorical: system.dataViz.categorical, sequential: system.dataViz.sequential },
    // Print is deliberately not a CSS token: there is no CSS meaning for a
    // Pantone. It rides in the machine formats so a print vendor can be sent
    // one file, and it is set out properly in the book.
    print: system.print.swatches.map((w) => ({
      role: w.role, hex: w.hex, cmyk: w.cmykString, computed: w.computed,
      pantoneCoated: w.pantoneCoated, ral: w.ral, verified: w.verified,
    })),
    breakpoint: Object.fromEntries(system.layout.breakpoints.map((b) => [b.name, b.px])),
    layout: { contentMax: system.layout.contentMaxPx, gutter: system.layout.gutterPx },
    duration: Object.fromEntries(system.motion.durations.map((d) => [d.name, d.ms])),
    easing: Object.fromEntries(Object.entries(system.motion.easings).map(([k, v]) => [k, v.value])),
  };
  return [
    '// Design tokens. Generated by Brandi. Edit the brand file, not this.',
    '// Prefer the CSS custom properties where you can: they theme without a re-render.',
    '',
    `export const tokens = ${JSON.stringify(body, null, 2)} as const;`,
    '',
    'export type Tokens = typeof tokens;',
    "export type SemanticToken = keyof Tokens['semantic']['light'];",
    'export default tokens;',
    '',
  ].join('\n');
}

export default { toDtcg, toCss, toTailwind, toTypeScript, cssVar };
